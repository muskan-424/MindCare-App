function formatLangBlock(code, pack) {
  const lines = [`  ${code}: {`];
  for (const [key, value] of Object.entries(pack)) {
    if (Array.isArray(value)) {
      lines.push(`    ${key}: [${value.map((v) => `'${v.replace(/'/g, "\\'")}'`).join(', ')}],`);
    } else {
      lines.push(`    ${key}: '${value.replace(/'/g, "\\'")}',`);
    }
  }
  lines.push('  },');
  return lines.join('\n');
}

